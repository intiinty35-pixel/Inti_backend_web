async function main() {
  const agent = await prisma.user.findUnique({ where: { email: (process.env.DEMO_AGENT_EMAIL || "agente@inti.local").toLowerCase() } });
  const user = await prisma.user.findUnique({ where: { email: (process.env.DEMO_USER_EMAIL || "usuario@inti.local").toLowerCase() } });

  for (const property of demoProperties) {
    const ownerId = property.createdByRole === "USER" ? user?.id : agent?.id;
    await prisma.property.upsert({
      where: { slug: property.slug },
      update: {
        ownerId,
        createdByRole: property.createdByRole,
        status: "PUBLISHED",
        contactName: property.contactName,
        contactEmail: property.contactEmail,
        contactPhone: property.contactPhone,
        contactWhatsapp: property.contactWhatsapp,
      },
      create: {
        slug: property.slug,
        ownerId,
        createdByRole: property.createdByRole,
        operationType: property.operationType,
        propertyType: property.propertyType,
        title: property.title,
        description: property.description,
        price: property.price,
        currency: property.currency,
        negotiable: property.negotiable,
        maintenanceFee: property.maintenanceFee,
        status: "PUBLISHED",
        contactName: property.contactName,
        contactEmail: property.contactEmail,
        contactPhone: property.contactPhone,
        contactWhatsapp: property.contactWhatsapp,
        location: { create: property.location },
        details: { create: { ...property.details, specificDetails: JSON.stringify(property.details.specificDetails) } },
        amenities: { create: property.amenityCodes.map((code) => ({ code })) },
        media: { create: property.media },
      },
    });
    console.log(`Propiedad de prueba lista: ${property.title}`);
  }
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(async () => prisma.$disconnect());
